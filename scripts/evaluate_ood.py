"""How does the model behave on photos that are NOT saffron?  -> docs/ood/predictions.json

The classifier has no "not saffron" class, so it always answers with one of C1-C5. This runs it on the openly
licensed red thread / yarn / fabric photos in docs/ood/ (credits in docs/ood/credits.json) with the training
preprocessing and records whether the web app's low-confidence rule (top < 0.60 or top-2 margin < 0.20) fires.

Usage: python scripts/evaluate_ood.py
"""
from __future__ import annotations

import json

import numpy as np

from saffron_common import BEST_MODEL, CLASS_NAMES, ROOT, load_image_rgb, to_model_input

import keras  # noqa: E402

MIN_TOP, MIN_MARGIN = 0.60, 0.20  # web/src/lib/prediction.ts


def main() -> None:
    ood = ROOT / "docs" / "ood"
    credits = json.loads((ood / "credits.json").read_text(encoding="utf-8"))
    x = np.stack([to_model_input(load_image_rgb(ood / c["file"])[0]) for c in credits]).astype("float32")
    probs = keras.models.load_model(BEST_MODEL).predict(x, verbose=0)

    rows = []
    for c, p in zip(credits, probs):
        order = np.argsort(p)[::-1]
        top, runner = float(p[order[0]]), float(p[order[1]])
        pure = float(p[0] + p[1])
        rows.append({
            "file": c["file"],
            "predicted": CLASS_NAMES[order[0]],
            "top_probability": round(top, 4),
            "runner_up": CLASS_NAMES[order[1]],
            "runner_up_probability": round(runner, 4),
            "verdict": "pure" if pure >= 0.5 else "counterfeit",
            "pure_probability": round(pure, 4),
            "low_confidence": top < MIN_TOP or top - runner < MIN_MARGIN,
            "probabilities": [round(float(v), 4) for v in p],
        })
        print(f"{c['file']:38s} {rows[-1]['predicted']} {top:.3f} (runner-up {rows[-1]['runner_up']} {runner:.3f}) "
              f"verdict {rows[-1]['verdict']:11s} {'LOW CONFIDENCE' if rows[-1]['low_confidence'] else 'confident'}")

    flagged = sum(r["low_confidence"] for r in rows)
    out = {"description": "Predictions on non-saffron photos (see credits.json). Generated by scripts/evaluate_ood.py.",
           "low_confidence_rule": {"min_top_probability": MIN_TOP, "min_top2_margin": MIN_MARGIN},
           "flagged_low_confidence": flagged, "total": len(rows), "images": rows}
    (ood / "predictions.json").write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8")
    print(f"\n{flagged}/{len(rows)} flagged as low confidence -> docs/ood/predictions.json")


if __name__ == "__main__":
    main()
